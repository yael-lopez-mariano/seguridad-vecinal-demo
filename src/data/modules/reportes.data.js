const byId = (items, key, id) =>
  items.find((item) => Number(item[key]) === Number(id));

const fullName = (user) =>
  [
    user?.nombre,
    user?.apellidoPaterno ?? user?.apellidoP,
    user?.apellidoMaterno ?? user?.apellidoM,
  ]
    .filter(Boolean)
    .join(" ");

const createReporte = ({
  reporteID,
  usuarioID,
  tipoReporteID,
  titulo,
  descripcion,
  direccionTexto,
  latitud,
  longitud,
  esAnonimo = false,
  fechaCreacion,
  fechaActualizacion,
  visto = false,
  estado = "Pendiente",
  prioridad = "Media",
  imagen = null,
  tiposReporte,
  usuarios,
}) => {
  const usuario = byId(usuarios, "usuarioID", usuarioID) || {};
  const tipo = byId(tiposReporte, "tipoReporteID", tipoReporteID) || {};

  return {
    reporteID,
    usuarioID,
    tipoReporteID,
    titulo,
    descripcion,
    latitud,
    longitud,
    direccionTexto,
    esAnonimo,
    fechaCreacion,
    fechaActualizacion,
    visto,
    estado,
    prioridad,
    imagen,
    nombreUsuario: esAnonimo
      ? null
      : fullName(usuario) || usuario.usuario || `Usuario #${usuarioID}`,
    tipoReporte: tipo.nombre || "Otro",
    email: esAnonimo ? "" : usuario.email || "",
    telefono: esAnonimo ? "" : usuario.telefono || "",
    numeroCasa: esAnonimo ? "" : usuario.numeroCasa || "",
    calle: esAnonimo ? "" : usuario.calle || "",
  };
};

